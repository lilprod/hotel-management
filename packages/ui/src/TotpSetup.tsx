import { CopyOutlined, DownloadOutlined } from '@ant-design/icons';
import { Alert, Button, Flex, Input, Typography } from 'antd';
import QRCode from 'qrcode';
import { useEffect, useState } from 'react';
import type { FormEvent } from 'react';

import { saveBlob } from './api';

export interface TotpSetupLabels {
  scan: string;
  manual: string;
  qrAlt: string;
  code: string;
  codeHint: string;
  activate: string;
  copy: string;
  copied: string;
}

export interface TotpSetupProps {
  otpauthUri: string;
  secret: string;
  labels: TotpSetupLabels;
  busy?: boolean;
  /** Translated error of the last activation attempt. */
  error?: string | null;
  onActivate: (code: string) => void;
}

/** Renders the otpauth URI as an inline SVG QR code (generated locally, nothing leaves the page). */
export function QrCodeSvg({ value, label }: { value: string; label: string }) {
  const [svg, setSvg] = useState('');
  useEffect(() => {
    let live = true;
    QRCode.toString(value, { type: 'svg', margin: 1, width: 200, errorCorrectionLevel: 'M' })
      .then((s) => live && setSvg(s))
      .catch(() => live && setSvg(''));
    return () => {
      live = false;
    };
  }, [value]);
  return (
    <div
      role="img"
      aria-label={label}
      style={{ width: 200, height: 200, background: '#fff', borderRadius: 8, lineHeight: 0 }}
      // SVG generated by the qrcode library from our own URI.
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
}

/** Group a base32 secret in blocks of 4 for easier manual entry. */
export const groupSecret = (secret: string) => secret.replace(/(.{4})/g, '$1 ').trim();

export function TotpSetup({ otpauthUri, secret, labels, busy, error, onActivate }: TotpSetupProps) {
  const [code, setCode] = useState('');
  const [copied, setCopied] = useState(false);
  const submit = (e: FormEvent) => {
    e.preventDefault();
    onActivate(code.replace(/\s/g, ''));
  };
  return (
    <Flex vertical gap={16}>
      <Typography.Paragraph style={{ margin: 0 }}>{labels.scan}</Typography.Paragraph>
      <Flex gap={24} wrap align="flex-start">
        <QrCodeSvg value={otpauthUri} label={labels.qrAlt} />
        <Flex vertical gap={8} style={{ minWidth: 220, flex: 1 }}>
          <Typography.Text type="secondary">{labels.manual}</Typography.Text>
          <Flex gap={8} align="center" wrap>
            <Typography.Text code copyable={false} data-testid="totp-secret">
              {groupSecret(secret)}
            </Typography.Text>
            <Button
              size="small"
              icon={<CopyOutlined />}
              onClick={() => {
                void navigator.clipboard?.writeText(secret).then(() => setCopied(true));
              }}
            >
              {copied ? labels.copied : labels.copy}
            </Button>
          </Flex>
        </Flex>
      </Flex>
      <form noValidate onSubmit={submit}>
        <Flex vertical gap={8} style={{ maxWidth: 320 }}>
          <label htmlFor="totp-code">{labels.code}</label>
          <Input
            id="totp-code"
            inputMode="numeric"
            autoComplete="one-time-code"
            maxLength={7}
            value={code}
            onChange={(e) => setCode(e.target.value)}
            aria-describedby="totp-code-hint"
            aria-invalid={error ? true : undefined}
          />
          <Typography.Text id="totp-code-hint" type="secondary">
            {labels.codeHint}
          </Typography.Text>
          {error ? <Alert type="error" showIcon message={error} role="alert" /> : null}
          <Button type="primary" htmlType="submit" loading={busy} disabled={code.length < 6}>
            {labels.activate}
          </Button>
        </Flex>
      </form>
    </Flex>
  );
}

export interface BackupCodesLabels {
  title: string;
  warning: string;
  download: string;
  fileName: string;
}

/** The 10 single-use codes, shown once, with a plain-text download. */
export function BackupCodes({ codes, labels }: { codes: string[]; labels: BackupCodesLabels }) {
  return (
    <Flex vertical gap={12}>
      <Alert type="warning" showIcon message={labels.title} description={labels.warning} />
      <ul
        aria-label={labels.title}
        style={{
          columns: 2,
          maxWidth: 320,
          margin: 0,
          padding: '12px 16px 12px 32px',
          fontFamily: 'ui-monospace, SFMono-Regular, Menlo, monospace',
          border: '1px solid var(--ant-color-border, #d9d9d9)',
          borderRadius: 8,
        }}
      >
        {codes.map((c) => (
          <li key={c}>{c}</li>
        ))}
      </ul>
      <div>
        <Button
          icon={<DownloadOutlined />}
          onClick={() =>
            saveBlob(
              new Blob([`${codes.join('\n')}\n`], { type: 'text/plain;charset=utf-8' }),
              labels.fileName,
            )
          }
        >
          {labels.download}
        </Button>
      </div>
    </Flex>
  );
}
