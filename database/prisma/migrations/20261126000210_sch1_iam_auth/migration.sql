-- ─────────────────────────── 3. Data migration ───────────────────────────
-- 3.1 Password history: settings (USER scope, key `_iam.password_history`, JSON array newest
-- first) → rows; the array order is kept through created_at.
INSERT INTO "password_history" (id, tenant_id, user_id, hash, created_at)
SELECT gen_random_uuid(), u.tenant_id, u.id, h.hash, s.updated_at - (h.ord * interval '1 millisecond')
  FROM "settings" s
  JOIN "users" u ON u.id = s.scope_id AND u.tenant_id = s.tenant_id
  CROSS JOIN LATERAL jsonb_array_elements_text(
    CASE WHEN jsonb_typeof(s.value) = 'array' THEN s.value ELSE '[]'::jsonb END)
    WITH ORDINALITY AS h(hash, ord)
 WHERE s.scope = 'USER' AND s.key = '_iam.password_history';

-- 3.2 MFA backup codes (hashes; codes already consumed were removed from the array).
INSERT INTO "mfa_backup_codes" (id, tenant_id, user_id, code_hash, created_at)
SELECT DISTINCT ON (u.id, c.hash) gen_random_uuid(), u.tenant_id, u.id, c.hash, s.updated_at
  FROM "settings" s
  JOIN "users" u ON u.id = s.scope_id AND u.tenant_id = s.tenant_id
  CROSS JOIN LATERAL jsonb_array_elements_text(
    CASE WHEN jsonb_typeof(s.value) = 'array' THEN s.value ELSE '[]'::jsonb END) AS c(hash)
 WHERE s.scope = 'USER' AND s.key = '_iam.mfa_backup_codes';

-- 3.3 Same for platform users (platform_settings `_platform_user.<id>.<key>`).
INSERT INTO "platform_password_history" (id, platform_user_id, hash, created_at)
SELECT gen_random_uuid(), pu.id, h.hash, ps.updated_at - (h.ord * interval '1 millisecond')
  FROM "platform_settings" ps
  JOIN "platform_users" pu ON ps.key = '_platform_user.' || pu.id::text || '.password_history'
  CROSS JOIN LATERAL jsonb_array_elements_text(
    CASE WHEN jsonb_typeof(ps.value) = 'array' THEN ps.value ELSE '[]'::jsonb END)
    WITH ORDINALITY AS h(hash, ord);
INSERT INTO "platform_mfa_backup_codes" (id, platform_user_id, code_hash, created_at)
SELECT DISTINCT ON (pu.id, c.hash) gen_random_uuid(), pu.id, c.hash, ps.updated_at
  FROM "platform_settings" ps
  JOIN "platform_users" pu ON ps.key = '_platform_user.' || pu.id::text || '.mfa_backup_codes'
  CROSS JOIN LATERAL jsonb_array_elements_text(
    CASE WHEN jsonb_typeof(ps.value) = 'array' THEN ps.value ELSE '[]'::jsonb END) AS c(hash);

-- 3.4 Permission version: settings (TENANT scope, `_iam.perm_ver`) → tenants.perm_ver.
UPDATE "tenants" t SET perm_ver = GREATEST(0, (s.value #>> '{}')::int)
  FROM "settings" s
 WHERE s.scope = 'TENANT' AND s.scope_id = t.id AND s.key = '_iam.perm_ver'
   AND jsonb_typeof(s.value) = 'number';

-- The workaround keys are gone (never exposed by the settings APIs).
DELETE FROM "settings" WHERE key IN ('_iam.password_history', '_iam.mfa_backup_codes', '_iam.perm_ver',
  '_portal.password_history', '_portal.mfa_backup_codes');
DELETE FROM "platform_settings" WHERE key ~ '^_platform_user\.[0-9a-f-]{36}\.(password_history|mfa_backup_codes)$';

-- 3.5 Impersonation sessions: user_agent "[impersonation] <agent e-mail>" → kind + impersonated_by.
UPDATE "sessions" s SET
  kind = 'IMPERSONATION',
  impersonated_by = pu.id,
  user_agent = NULL,
  revoked_at = CASE WHEN pu.id IS NULL THEN COALESCE(s.revoked_at, now()) ELSE s.revoked_at END
  FROM "sessions" s2
  LEFT JOIN "platform_users" pu ON lower(pu.email) = lower(btrim(substr(s2.user_agent, length('[impersonation]') + 1)))
 WHERE s2.id = s.id AND s2.user_agent LIKE '[impersonation]%';

-- 3.6 Self-signup owners waiting for their e-mail verification: INVITED + password hash
-- (admin invitations never carry a password) → PENDING_VERIFICATION.
UPDATE "users" SET status = 'PENDING_VERIFICATION'
 WHERE status = 'INVITED' AND password_hash IS NOT NULL AND deleted_at IS NULL;
